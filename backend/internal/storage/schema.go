// Package storage owns the DynamoDB table schema and data access for inventory and
// reservations.
package storage

import (
	"fmt"
	"os"
)

// Inventory table: one item per card, keyed by card ID.
const (
	InventoryKeyCardID = "cardId" // partition key
	InventoryName      = "name"
	InventoryRarity    = "rarity"
	InventoryStock     = "stock" // never negative; decremented only under a condition
)

// Reservations table: one outcome per trainer and request ID. Keying by trainer makes
// "trainers read only their own reservations" a structural property of every lookup.
const (
	ReservationKeyTrainerID = "trainerId" // partition key (token sub claim)
	ReservationKeyRequestID = "requestId" // sort key
	ReservationCardID       = "cardId"
	ReservationStatus       = "status"
	ReservationUpdatedAt    = "updatedAt"
)

// Environment variables carrying table names. The names are generated by CloudFormation, so
// code must never hard-code them.
const (
	EnvInventoryTable    = "INVENTORY_TABLE"
	EnvReservationsTable = "RESERVATIONS_TABLE"
)

// TableNames are the deployed DynamoDB table names.
type TableNames struct {
	Inventory    string
	Reservations string
}

// TableNamesFromEnv reads the table names from the environment.
func TableNamesFromEnv() (TableNames, error) {
	inv := os.Getenv(EnvInventoryTable)
	if inv == "" {
		return TableNames{}, fmt.Errorf("%s is not set", EnvInventoryTable)
	}
	res := os.Getenv(EnvReservationsTable)
	if res == "" {
		return TableNames{}, fmt.Errorf("%s is not set", EnvReservationsTable)
	}
	return TableNames{Inventory: inv, Reservations: res}, nil
}
